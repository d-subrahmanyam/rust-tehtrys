/// Glyph rows for a char. lowercase→lowercase glyph (provided); unknown→space.
pub fn glyph(c: char) -> [u8; 8] {
    let code = c as u32;
    if (0x20..=0x7E).contains(&code) {
        FONT[(code - 0x20) as usize]
    } else {
        FONT[0]
    }
}

