#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn font_table_len_95() {
        assert_eq!(FONT.len(), 95);
    }

    #[test]
    fn printable_has_some_pixels() {
        // 'A' (0x41) has pixels; space empty. (sanity, not visual proof)
        assert!(glyph('A').iter().any(|&r| r != 0));
        assert!(glyph('0').iter().any(|&r| r != 0));
        assert!(glyph(' ').iter().all(|&r| r == 0));
    }
}
